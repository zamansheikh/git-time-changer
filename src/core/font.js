const mirror = (rows) => rows.map((row) => [...row].reverse().join(''));
const rotate = (rows) => mirror([...rows].reverse());

// Glyphs that are another glyph flipped.
const DERIVED = {
  ')': mirror(PUNCTUATION['(']),
  '>': mirror(PUNCTUATION['<']),
  ']': mirror(PUNCTUATION['[']),
  '}': mirror(PUNCTUATION['{']),
  '\\': mirror(PUNCTUATION['/']),
  '¡': rotate(PUNCTUATION['!']),
  '¿': rotate(PUNCTUATION['?']),
};

// Accented lowercase letters: a 2-row accent above the x-height of the base letter.
const ACCENTS = {
  '́': { 5: ['...#.', '..#..'], 3: ['..#', '.#.'] }, // acute  á
  '̀': { 5: ['.#...', '..#..'], 3: ['#..', '.#.'] }, // grave  à
  '̂': { 5: ['..#..', '.#.#.'], 3: ['.#.', '#.#'] }, // circumflex  â
  '̈': { 5: ['.#.#.', '.....'], 3: ['#.#', '...'] }, // diaeresis  ä
  '̃': { 5: ['.##.#', '#..#.'] }, // tilde  ã
};
const ACCENT_BASES = { a: LOWER.a, e: LOWER.e, o: LOWER.o, u: LOWER.u, n: LOWER.n, i: ['...', '...', ...LOWER.i.slice(2)] };

function accented() {
  const out = {};
  for (const [base, rows] of Object.entries(ACCENT_BASES)) {
    for (const [mark, shapes] of Object.entries(ACCENTS)) {
      const ch = (base + mark).normalize('NFC');
      const accent = shapes[rows[0].length];
      if (ch.length === 1 && accent) out[ch] = [...accent, ...rows.slice(2)];
    }
  }
  return out;
}

const FONT = { ...UPPER, ...LOWER, ...DIGITS, ...PUNCTUATION, ...DERIVED, ...accented() };

// Look-alikes for characters the font doesn't draw directly.
const REPLACEMENTS = [
  [/[‘’‚′]/g, "'"],
  [/[“”„″]/g, '"'],
  [/[–—−]/g, '-'],
  [/…/g, '...'],
  [/[❤♡]️?/g, '♥'],
  [/[☆⭐]️?/g, '★'],
  [/ß/g, 'ss'],
  [/æ/g, 'ae'],
  [/Æ/g, 'AE'],
  [/œ/g, 'oe'],
  [/Œ/g, 'OE'],
  [/ø/g, 'o'],
  [/Ø/g, 'O'],
  [/ł/g, 'l'],
  [/Ł/g, 'L'],
  [/×/g, 'x'],
];

const SUPPORTED = 'letters (a–z, A–Z, common accents), digits, punctuation, € £ ♥ ★';

// Drops accents the font has no room for: É -> E, ç -> c.
function stripAccents(ch) {
  return ch.normalize('NFD').replace(/\p{M}/gu, '');
}

// Cleans up the text and checks every character can be drawn.
function normalize(text) {
  let out = String(text);
  for (const [pattern, to] of REPLACEMENTS) out = out.replace(pattern, to);
  out = out.replace(/\s+/g, ' ').trim();
  out = [...out].map((ch) => (FONT[ch] ? ch : FONT[stripAccents(ch)] ? stripAccents(ch) : ch)).join('');
  const missing = [...new Set([...out].filter((ch) => !FONT[ch]))];
  if (missing.length) {
    throw new RangeError(`Can't draw ${missing.map((ch) => `"${ch}"`).join(', ')}. Supported: ${SUPPORTED}.`);
  }
  return out;
}

/**
 * Text -> columns of 7 booleans (one column per week, top row is Sunday),
 * with one empty column between characters.
 */
function renderText(text) {
  const chars = [...normalize(text)];
  const columns = [];
  chars.forEach((ch, i) => {
    const rows = FONT[ch];
    for (let x = 0; x < rows[0].length; x++) columns.push(rows.map((row) => row[x] === '#'));
    if (i < chars.length - 1) columns.push(Array(7).fill(false));
  });
  return columns;
}

module.exports = { FONT, SUPPORTED, normalize, renderText };
